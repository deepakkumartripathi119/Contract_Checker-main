"""
core/citation_verifier.py — Deterministic verification of LLM-generated citations.

Purpose
-------
LLMs often hallucinate or misquote policy documents when generating citations.
This module verifies whether an exact_policy_quote provided by the LLM is an
authentic verbatim quote from the retrieved policy documents before it is
presented to the user.

Verification Strategy
---------------------
1. Text normalization: Lowercases, collapses whitespace, and removes surrounding
   punctuation and formatting artifacts.
2. Direct substring match: Checks whether the normalized quote exists inside
   any of the retrieved policy document texts.
3. Word-sequence match: Checks whether the sequence of normalized words appears
   contiguously in the document (robust against PDF line-breaks and hyphens).
4. Tagging & Safeguards: If unverified, sets citation_verified=False and prepends
   a warning tag to the reason field.
"""

from __future__ import annotations

import re
from typing import Optional
from langchain.schema import Document


def normalize_for_matching(text: str) -> str:
    """Normalize text for substring matching: lowercase, alphanumeric and spaces only."""
    text = text.lower()
    # Replace non-alphanumeric characters with space
    text = re.sub(r"[^\w\s]", " ", text)
    # Collapse multiple whitespace characters into a single space
    return re.sub(r"\s+", " ", text).strip()


def clean_quote_formatting(quote: str) -> str:
    """Remove Markdown/PDF presentation markers without changing quote wording."""
    cleaned = quote.strip().strip("\"'“”«»`")
    cleaned = re.sub(r"(?m)^\s*\[Page\s+\d+\]\s*$", "", cleaned)
    cleaned = re.sub(r"(?m)^\s*#{1,6}\s+", "", cleaned)
    cleaned = re.sub(r"(?m)^\s*[*_`]+([^*_`]+)[*_`]+\s*$", r"\1", cleaned)
    return re.sub(r"\n{3,}", "\n\n", cleaned).strip()


def verify_citation(
    quote: Optional[str],
    documents: list[Document],
    min_word_length: int = 3,
) -> tuple[bool, Optional[str]]:
    """
    Deterministically verify if `quote` is a verbatim excerpt of any document in `documents`.

    Parameters
    ----------
    quote           : exact verbatim quote generated by the LLM (or None)
    documents       : list of retrieved policy Document objects
    min_word_length : retained for API compatibility; short quotes are verified too

    Returns
    -------
    (is_verified, cleaned_quote)
      is_verified   : True if quote exists verbatim in at least one document
      cleaned_quote : stripped and cleaned quote string, or None
    """
    if not quote or not quote.strip():
        return True, None

    cleaned_quote = clean_quote_formatting(quote)
    if not cleaned_quote:
        return True, None

    norm_quote = normalize_for_matching(cleaned_quote)
    quote_words = norm_quote.split()

    for doc in documents:
        norm_doc = normalize_for_matching(doc.page_content)

        # 1. Exact normalized substring match
        if norm_quote in norm_doc:
            return True, cleaned_quote

        # 2. Contiguous word sequence check
        doc_words = norm_doc.split()
        q_len = len(quote_words)
        for i in range(len(doc_words) - q_len + 1):
            if doc_words[i:i + q_len] == quote_words:
                return True, cleaned_quote

    # Quote was not found in any retrieved document
    return False, cleaned_quote


def verify_compliance_result(
    result: dict,
    documents: list[Document],
) -> dict:
    """
    Validate and annotate a compliance result dict with citation verification.

    If exact_policy_quote is unverified:
      - Sets citation_verified = False
      - Prepends "[CITATION UNVERIFIED]" warning to the reason field
    """
    quote = result.get("exact_policy_quote")
    if not quote or not str(quote).strip():
        if result.get("compliant") is False:
            result["citation_verified"] = False
            curr_reason = result.get("reason", "")
            if "[CITATION UNVERIFIED - Missing Quote]" not in curr_reason:
                result["reason"] = (
                    f"[CITATION UNVERIFIED - Missing Quote] {curr_reason}"
                )
        else:
            result["citation_verified"] = None
        return result

    is_verified, clean_quote = verify_citation(quote, documents)
    result["citation_verified"] = is_verified
    result["exact_policy_quote"] = clean_quote

    if not is_verified:
        curr_reason = result.get("reason", "")
        if "[CITATION UNVERIFIED]" not in curr_reason:
            result["reason"] = f"[CITATION UNVERIFIED] {curr_reason}"

    return result
